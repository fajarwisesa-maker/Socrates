"""v2 step 1: package the mock S/4HANA for SAP BTP Cloud Foundry -> build/btp/.

    uv run python scripts/package_btp.py      # or: make btp-package
    cd build/btp && cf push --no-start
    cf set-env siaga-sap-mock SAP_MOCK_API_KEY ... && cf start siaga-sap-mock

Only what the mock needs goes in: services/sap_mock (without the in-process helper),
siaga_common, data/seed, a pinned requirements.txt, runtime.txt and manifest.yml.
The SQLite file is ephemeral on CF; the app seeds itself on start and POST /admin/reset
re-seeds it (`make demo-reset` calls it when SAP_MOCK_ON_BTP=1).
"""

from __future__ import annotations

import importlib.metadata as md
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "btp"
APP = "siaga-sap-mock"
FILES = [
    "services/__init__.py",
    "services/sap_mock/__init__.py",
    "services/sap_mock/app.py",
    "services/sap_mock/odata.py",
    "services/sap_mock/seed.py",
    "services/sap_mock/store.py",
    "siaga_common/__init__.py",
    "siaga_common/settings.py",
    "siaga_common/timeline.py",
]
# exact versions from this repo's uv-locked environment
REQUIREMENTS = ["fastapi", "uvicorn", "pydantic", "pydantic-settings", "python-dotenv"]

CMD = "python -m uvicorn --factory services.sap_mock.app:create_app --host 0.0.0.0 --port $PORT"
MANIFEST = f"""---
# SIAGA mock S/4HANA on SAP BTP Cloud Foundry (v2 step 1). Generated by scripts/package_btp.py.
applications:
  - name: {APP}
    memory: 512M
    instances: 1
    buildpacks:
      - python_buildpack
    # random-route: a unique host on the landscape's shared domain (the org is shared)
    random-route: true
    # port health check: every HTTP endpoint requires X-API-Key, including any /health
    health-check-type: port
    command: {CMD}
    env:
      SAP_DB_PATH: var/sap_mock.db
      # SAP_MOCK_API_KEY is set with `cf set-env`, never in this file
"""


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    for f in FILES:
        dst = OUT / f
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(ROOT / f, dst)
    shutil.copytree(ROOT / "data" / "seed", OUT / "data" / "seed")
    (OUT / "requirements.txt").write_text(
        "".join(f"{p}=={md.version(p)}\n" for p in REQUIREMENTS), encoding="utf-8"
    )
    (OUT / "runtime.txt").write_text("python-3.12.x\n", encoding="utf-8")
    (OUT / "manifest.yml").write_text(MANIFEST, encoding="utf-8")
    (OUT / ".cfignore").write_text("__pycache__/\n*.pyc\nvar/\n", encoding="utf-8")
    n = sum(1 for p in OUT.rglob("*") if p.is_file())
    print(f"{n} files -> {OUT}  (app {APP})")
    print((OUT / "requirements.txt").read_text(encoding="utf-8").strip())


if __name__ == "__main__":
    main()
